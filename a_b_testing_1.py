diff = p2 - p1

# pooled proportion для H0
p_pool = (x1 + x2) / (n1 + n2)
se = np.sqrt(p_pool * (1 - p_pool) * (1 / n1 + 1 / n2))

z = diff / se
p_value = 2 * (1 - stats.norm.cdf(abs(z))) # т.к. z < 0, вычитаем из 1 z по модулю

